-- ORDEN (Órdenes de los clientes)
CREATE TABLE ORDEN(
  ID_ORDEN             NUMBER         NOT NULL,
  ID_MESA              NUMBER,
  ID_SECCION           NUMBER         NOT NULL,
  ID_CLIENTE           NUMBER,
  ID_USUARIO_SALONERO  NUMBER         NOT NULL,
