  END IF;
  -- Generar número de orden automático
  IF :NEW.NUMERO_ORDEN IS NULL THEN
    :NEW.NUMERO_ORDEN := 'ORD-' || TO_CHAR(SYSDATE, 'YYYYMMDD') || '-' || LPAD(:NEW.ID_ORDEN, 6, '0');
  END IF;
END;
/
