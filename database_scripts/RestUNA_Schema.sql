-- USUARIO
CREATE OR REPLACE TRIGGER ts_Usuario_SEQ_USUARIO
BEFORE INSERT ON USUARIO FOR EACH ROW
BEGIN
  IF :NEW.ID_USUARIO IS NULL OR :NEW.ID_USUARIO <= 0 THEN
    :NEW.ID_USUARIO := SEQ_USUARIO.NEXTVAL;
  END IF;
END;
/
CREATE OR REPLACE TRIGGER tsu_Usuario_SEQ_USUARIO
AFTER UPDATE OF ID_USUARIO ON USUARIO FOR EACH ROW
BEGIN
  RAISE_APPLICATION_ERROR(-20001,'No se puede modificar ID_USUARIO (secuencia).');
END;
/

