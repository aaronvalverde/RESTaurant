  SUBTOTAL             NUMBER(12,2)   NOT NULL,
  IMPUESTO_VENTA       NUMBER(10,2)   DEFAULT 0 NOT NULL,
  IMPUESTO_SERVICIO    NUMBER(10,2)   DEFAULT 0 NOT NULL,
  DESCUENTO            NUMBER(10,2)   DEFAULT 0 NOT NULL,
