-- USUARIO (Administradores, Cajeros, Saloneros)
CREATE TABLE USUARIO(
  ID_USUARIO           NUMBER         NOT NULL,
  USUARIO              VARCHAR2(50)   NOT NULL,
  NOMBRE               VARCHAR2(100)  NOT NULL,
  CONTRASENA           VARCHAR2(255)  NOT NULL,
  ROL                  VARCHAR2(20)   NOT NULL,
  ESTADO               CHAR(1)        NOT NULL,
  FECHA_CREACION       DATE           DEFAULT SYSDATE NOT NULL,
  FECHA_ULTIMO_ACCESO  DATE,
  TOKEN_SESION         VARCHAR2(500),
  CONSTRAINT PK_USUARIO           PRIMARY KEY (ID_USUARIO),
  CONSTRAINT UQ_USUARIO_USUARIO   UNIQUE (USUARIO),
  CONSTRAINT CHK_USUARIO_ROL      CHECK (ROL IN ('ADMINISTRADOR','CAJERO','SALONERO')),
  CONSTRAINT CHK_USUARIO_ESTADO   CHECK (ESTADO IN ('A','I'))
);

-- SECCION (Salones, Barra, etc.)
CREATE TABLE SECCION(
  ID_SECCION           NUMBER         NOT NULL,
  NOMBRE               VARCHAR2(80)   NOT NULL,
  TIPO                 VARCHAR2(15)   NOT NULL,
  COBRA_IMPUESTO       CHAR(1)        NOT NULL,
  ESTADO               CHAR(1)        NOT NULL,
  FECHA_CREACION       DATE           DEFAULT SYSDATE NOT NULL,
  ID_ARCHIVO_IMAGEN    NUMBER,
  CONSTRAINT PK_SECCION           PRIMARY KEY (ID_SECCION),
  CONSTRAINT UQ_SECCION_NOMBRE    UNIQUE (NOMBRE),
  CONSTRAINT CHK_SECCION_TIPO     CHECK (TIPO IN ('SALON','BARRA','TERRAZA')),
  CONSTRAINT CHK_SECCION_IMPUESTO CHECK (COBRA_IMPUESTO IN ('S','N')),
  CONSTRAINT CHK_SECCION_ESTADO   CHECK (ESTADO IN ('A','I'))
);

-- MESA (Mesas de los salones)
CREATE TABLE MESA(
  ID_MESA              NUMBER         NOT NULL,
  ID_SECCION           NUMBER         NOT NULL,
  NUMERO_MESA          VARCHAR2(10)   NOT NULL,
  CAPACIDAD            NUMBER(2)      NOT NULL,
  POSICION_X           NUMBER(5,2),
  POSICION_Y           NUMBER(5,2),
  ESTADO               VARCHAR2(10)   NOT NULL,
  FECHA_CREACION       DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_MESA              PRIMARY KEY (ID_MESA),
  CONSTRAINT UQ_MESA_SECCION      UNIQUE (ID_SECCION, NUMERO_MESA),
  CONSTRAINT CHK_MESA_CAPACIDAD   CHECK (CAPACIDAD BETWEEN 1 AND 20),
  CONSTRAINT CHK_MESA_ESTADO      CHECK (ESTADO IN ('LIBRE','OCUPADA','RESERVADA','FUERA_SERVICIO'))
);

-- GRUPO_PRODUCTO (Categorías del menú)
CREATE TABLE GRUPO_PRODUCTO(
  ID_GRUPO_PRODUCTO    NUMBER         NOT NULL,
  NOMBRE               VARCHAR2(80)   NOT NULL,
  DESCRIPCION          VARCHAR2(200),
  ACCESO_RAPIDO        CHAR(1)        NOT NULL,
  ORDEN_VISUALIZACION  NUMBER(3)      NOT NULL,
  CANTIDAD_VENDIDA     NUMBER(10)     DEFAULT 0 NOT NULL,
  ESTADO               CHAR(1)        NOT NULL,
  FECHA_CREACION       DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_GRUPO_PRODUCTO        PRIMARY KEY (ID_GRUPO_PRODUCTO),
  CONSTRAINT UQ_GRUPO_NOMBRE          UNIQUE (NOMBRE),
  CONSTRAINT CHK_GRUPO_ACCESO         CHECK (ACCESO_RAPIDO IN ('S','N')),
  CONSTRAINT CHK_GRUPO_ESTADO         CHECK (ESTADO IN ('A','I'))
);

-- PRODUCTO (Productos del menú)
CREATE TABLE PRODUCTO(
  ID_PRODUCTO          NUMBER         NOT NULL,
  ID_GRUPO_PRODUCTO    NUMBER         NOT NULL,
  NOMBRE               VARCHAR2(120)  NOT NULL,
  NOMBRE_CORTO         VARCHAR2(30)   NOT NULL,
  DESCRIPCION          VARCHAR2(300),
  PRECIO               NUMBER(10,2)   NOT NULL,
  ACCESO_RAPIDO        CHAR(1)        NOT NULL,
  CANTIDAD_VENDIDA     NUMBER(10)     DEFAULT 0 NOT NULL,
  ESTADO               CHAR(1)        NOT NULL,
  FECHA_CREACION       DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_PRODUCTO              PRIMARY KEY (ID_PRODUCTO),
  CONSTRAINT UQ_PRODUCTO_NOMBRE       UNIQUE (NOMBRE),
  CONSTRAINT UQ_PRODUCTO_CORTO        UNIQUE (NOMBRE_CORTO),
  CONSTRAINT CHK_PRODUCTO_PRECIO      CHECK (PRECIO > 0),
  CONSTRAINT CHK_PRODUCTO_ACCESO      CHECK (ACCESO_RAPIDO IN ('S','N')),
  CONSTRAINT CHK_PRODUCTO_ESTADO      CHECK (ESTADO IN ('A','I'))
);

-- CLIENTE (Información de clientes)
CREATE TABLE CLIENTE(
  ID_CLIENTE           NUMBER         NOT NULL,
  NOMBRE               VARCHAR2(100),
  APELLIDOS            VARCHAR2(120),
