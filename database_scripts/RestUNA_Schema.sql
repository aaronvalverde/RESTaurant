  TARJETA_RECIBIDO     NUMBER(12,2)   DEFAULT 0 NOT NULL,
  VUELTO               NUMBER(10,2)   DEFAULT 0 NOT NULL,
  ESTADO               VARCHAR2(15)   NOT NULL,
  CORREO_ENVIADO       CHAR(1)        DEFAULT 'N' NOT NULL,
  CONSTRAINT PK_FACTURA               PRIMARY KEY (ID_FACTURA),
  CONSTRAINT UQ_FACTURA_NUMERO        UNIQUE (NUMERO_FACTURA),
  CONSTRAINT CHK_FACTURA_SUBTOTAL     CHECK (SUBTOTAL >= 0),
  CONSTRAINT CHK_FACTURA_TOTAL        CHECK (TOTAL >= 0),
  CONSTRAINT CHK_FACTURA_ESTADO       CHECK (ESTADO IN ('ACTIVA','ANULADA')),
  CONSTRAINT CHK_FACTURA_CORREO       CHECK (CORREO_ENVIADO IN ('S','N'))
