-- Actualizar estado de mesa cuando se crea/modifica orden
CREATE OR REPLACE TRIGGER tr_Orden_Estado_Mesa
AFTER INSERT OR UPDATE OR DELETE ON ORDEN FOR EACH ROW
BEGIN
  -- Actualizar estado de mesa al insertar orden
  IF INSERTING AND :NEW.ID_MESA IS NOT NULL THEN
    UPDATE MESA SET ESTADO = 'OCUPADA' 
    WHERE ID_MESA = :NEW.ID_MESA AND ESTADO = 'LIBRE';
  END IF;
  
  -- Actualizar estado de mesa al cambiar estado de orden
  IF UPDATING AND :NEW.ESTADO = 'FACTURADA' AND :NEW.ID_MESA IS NOT NULL THEN
    UPDATE MESA SET ESTADO = 'LIBRE' 
    WHERE ID_MESA = :NEW.ID_MESA;
  END IF;
  
  -- Liberar mesa al eliminar orden
  IF DELETING AND :OLD.ID_MESA IS NOT NULL THEN
    UPDATE MESA SET ESTADO = 'LIBRE' 
    WHERE ID_MESA = :OLD.ID_MESA;
  END IF;
END;
/

-- Actualizar subtotal de orden al modificar detalles
CREATE OR REPLACE TRIGGER tr_DetalleOrden_Actualizar_Subtotal
AFTER INSERT OR UPDATE OR DELETE ON DETALLE_ORDEN FOR EACH ROW
DECLARE
  v_subtotal NUMBER(10,2);
BEGIN
  -- Calcular nuevo subtotal de la orden
  IF INSERTING OR UPDATING THEN
    SELECT NVL(SUM(SUBTOTAL), 0) INTO v_subtotal 
    FROM DETALLE_ORDEN WHERE ID_ORDEN = :NEW.ID_ORDEN;
    
    UPDATE ORDEN SET SUBTOTAL = v_subtotal 
    WHERE ID_ORDEN = :NEW.ID_ORDEN;
  END IF;
  
  IF DELETING THEN
    SELECT NVL(SUM(SUBTOTAL), 0) INTO v_subtotal 
    FROM DETALLE_ORDEN WHERE ID_ORDEN = :OLD.ID_ORDEN;
    
    UPDATE ORDEN SET SUBTOTAL = v_subtotal 
    WHERE ID_ORDEN = :OLD.ID_ORDEN;
  END IF;
END;
/

-- Actualizar contador de ventas de productos
CREATE OR REPLACE TRIGGER tr_DetalleFactura_Contador_Ventas
AFTER INSERT ON DETALLE_FACTURA FOR EACH ROW
BEGIN
  -- Actualizar contador del producto
  UPDATE PRODUCTO 
  SET CANTIDAD_VENDIDA = CANTIDAD_VENDIDA + :NEW.CANTIDAD
  WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;
  
  -- Actualizar contador del grupo
  UPDATE GRUPO_PRODUCTO 
  SET CANTIDAD_VENDIDA = CANTIDAD_VENDIDA + :NEW.CANTIDAD
  WHERE ID_GRUPO_PRODUCTO = (
    SELECT ID_GRUPO_PRODUCTO FROM PRODUCTO WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
  );
END;
/

